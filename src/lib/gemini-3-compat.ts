import { supportsThinkingBudget } from "./models";

// Compatibility bridge for Gemini 3.x models with the pinned @ai-sdk/google
// (1.2.x), which predates Gemini 3:
//
// 1. Thinking level. The SDK's zod schema strips `thinkingLevel` from
//    providerOptions, but Gemini 3.x models are configured with thinking
//    levels and can never disable thinking. Left alone, their default
//    (medium) thinking consumes the entire maxTokens budget before the first
//    tool call (observed: finishReason "length", 0 tool calls, ~38s on the
//    free tier). This wrapper injects generationConfig.thinkingConfig.
//    thinkingLevel "low" into outgoing requests.
//
// 2. Thought signatures. Gemini 3.x returns an opaque `thoughtSignature`
//    alongside function calls and rejects follow-up requests whose history
//    contains functionCall parts without one (400 "Function call is missing
//    a thought_signature"). The SDK strips signatures when parsing parts and
//    never echoes them back, so multi-step tool flows die on step 2. The
//    wrapper captures signatures from streamed responses and injects the
//    latest one into outgoing functionCall parts that lack a signature.
//    Signatures are scoped per model: they are endpoint/model-bound opaque
//    tokens, and Google hard-rejects foreign signatures on newer 3.x models
//    ("Thought signature is not valid" / "Corrupted thought signature" —
//    observed on mid-conversation model failover; see vercel/ai issues
//    #14196, #32140). When no signature was observed for this model, this
//    bridge falls back to the documented sentinel
//    "skip_thought_signature_validator", which the API accepts (with
//    degraded reasoning) for tool-call replays that were not generated by
//    the model — e.g. history transferred from a different model.
//    This is a bridge until an SDK that natively supports Gemini 3 (ai v5)
//    lands.

// "low" is the lowest thinking level the Flash models support while still
// producing thought summaries: at "minimal" the model barely thinks, so
// includeThoughts yields nothing and the chain of thought stays invisible.
// The Lite variants only support "minimal" (their documented default) —
// sending "low" makes the endpoint stall with no response at all (observed:
// streamGenerateContent opens but never emits headers or bytes), so Lite
// models get "minimal". Trade-off: summary-less thinking, but the request
// completes.
const THINKING_LEVEL = "low";
const THINKING_LEVEL_LITE = "minimal";

// Lite models (e.g. gemini-3.1-flash-lite, gemini-3.5-flash-lite) reject/ignore "low".
function thinkingLevelFor(modelId: string): string {
  return /-lite(-preview)?$/.test(modelId) ? THINKING_LEVEL_LITE : THINKING_LEVEL;
}

// Signatures are scoped per model: keyed by model id, then tool name.
// Gemini only hard-fails on missing signatures, so the latest observed
// signature per tool is good enough for a bridge. Never cross-inject a
// signature harvested from another model — newer 3.x endpoints reject
// foreign signatures with a 400 instead of degrading gracefully.
const signaturesByModel = new Map<string, Map<string, string>>();

// Latest observed signature on a non-functionCall part (e.g. the end of a
// thinking block), also per model.
const lastSignatureByModel = new Map<string, string>();

// Test helper: signature caches are module-globally scoped per model, and
// tests must start from a clean state so model-scoped isolation is observed.
export function resetGemini3SignatureState(): void {
  signaturesByModel.clear();
  lastSignatureByModel.clear();
}

// Documented dummy signatures for functionCall parts that were not generated
// by Gemini (e.g. history built by a different provider such as Groq, or
// transferred from a different Gemini model):
// https://ai.google.dev/gemini-api/docs/thought-signatures. The API accepts
// the sentinel and continues the turn (with degraded reasoning); only a
// missing signature is a hard 400.
const DUMMY_THOUGHT_SIGNATURE = "skip_thought_signature_validator";

function signaturesFor(modelId: string): Map<string, string> {
  let map = signaturesByModel.get(modelId);
  if (!map) {
    map = new Map();
    signaturesByModel.set(modelId, map);
  }
  return map;
}

function geminiModelIdFromUrl(url: string): string | undefined {
  return /\/models\/([\w.-]+):(streamGenerateContent|generateContent)/.exec(url)?.[1];
}

function injectThoughtSignatures(modelId: string, body: { contents?: unknown }): void {
  const signatures = signaturesFor(modelId);
  const lastSignature = lastSignatureByModel.get(modelId);
  for (const content of Array.isArray(body.contents) ? body.contents : []) {
    const parts = (content as { parts?: unknown })?.parts;
    if (!Array.isArray(parts)) continue;
    for (const part of parts) {
      const call = (part as { functionCall?: { name?: unknown } })?.functionCall;
      if (!call || typeof call.name !== "string") continue;
      if ((part as { thoughtSignature?: unknown }).thoughtSignature) continue;
      // Never reuse a signature harvested from a different model: newer
      // Gemini 3.x endpoints hard-reject foreign signatures with a 400
      // ("Thought signature is not valid"). Both name-bound and fallback
      // signatures come from THIS model's stream only.
      const signature =
        signatures.get(call.name) ?? lastSignature ?? DUMMY_THOUGHT_SIGNATURE;
      if (signature) {
        (part as { thoughtSignature?: string }).thoughtSignature = signature;
      }
    }
  }
}

interface GeminiChunkPart {
  functionCall?: { name?: unknown };
  thoughtSignature?: unknown;
  thought?: unknown;
  text?: unknown;
}

function harvestSignaturesFromSseChunk(modelId: string, chunk: string): void {
  const signatures = signaturesFor(modelId);
  for (const line of chunk.split("\n")) {
    if (!line.startsWith("data:")) continue;
    const payload = line.slice(5).trim();
    if (!payload || payload === "[DONE]") continue;
    try {
      const parsed = JSON.parse(payload) as {
        candidates?: { content?: { parts?: GeminiChunkPart[] } }[];
      };
      for (const part of parsed.candidates?.[0]?.content?.parts ?? []) {
        if (typeof part.thoughtSignature === "string" && part.thoughtSignature) {
          const name = part.functionCall?.name;
          if (typeof name === "string") {
            signatures.set(name, part.thoughtSignature);
          } else {
            // A signature on a non-functionCall part (e.g. the end of a
            // thinking block) — remember it as the fallback for the next
            // bare functionCall in this stream.
            lastSignatureByModel.set(modelId, part.thoughtSignature);
          }
        }
        if (part.functionCall?.name && typeof part.functionCall.name === "string") {
          const name = part.functionCall.name;
          if (!signatures.has(name) && lastSignatureByModel.get(modelId)) {
            signatures.set(name, lastSignatureByModel.get(modelId)!);
          }
        }
      }
    } catch {
      // Not JSON — ignore; signature harvesting is best-effort.
    }
  }
}

async function consumeForSignatures(
  modelId: string,
  stream: ReadableStream<Uint8Array>
): Promise<void> {
  try {
    const reader = stream.getReader();
    const decoder = new TextDecoder();
    let buffer = "";
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true });
      const lastNewline = buffer.lastIndexOf("\n");
      if (lastNewline === -1) continue;
      harvestSignaturesFromSseChunk(modelId, buffer.slice(0, lastNewline + 1));
      buffer = buffer.slice(lastNewline + 1);
    }
    harvestSignaturesFromSseChunk(modelId, buffer);
  } catch {
    // Best-effort harvesting — never break the caller's stream.
  }
}

export function createGemini3CompatFetch(): typeof fetch {
  return async (input, init) => {
    // Resolved lazily so patches applied after module evaluation (e.g.
    // instrumentation wrappers) are still honored.
    const rawFetch = globalThis.fetch;
    const url =
      typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
    const modelId = url ? geminiModelIdFromUrl(url) : undefined;

    // Gemini 2.5 models need no bridging: they take thinkingBudget via
    // providerOptions and don't use thought signatures.
    if (!modelId || supportsThinkingBudget(modelId)) {
      return rawFetch(input, init);
    }

    if (init?.body && typeof init.body === "string") {
      try {
        const body = JSON.parse(init.body) as {
          contents?: unknown;
          generationConfig?: Record<string, unknown>;
        };
        injectThoughtSignatures(modelId, body);
        body.generationConfig = {
          ...body.generationConfig,
          thinkingConfig: {
            thinkingLevel: thinkingLevelFor(modelId),
            // Stream thought summaries so the UI can show the model's chain
            // of thought while it works (MessageList renders reasoning
            // parts). Without this, thinking happens invisibly.
            includeThoughts: true,
          },
        };
        init = { ...init, body: JSON.stringify(body) };
      } catch {
        // Not valid JSON (unexpected) — pass the request through untouched.
        return rawFetch(input, init);
      }
    }

    const response = await rawFetch(input, init);

    // Tee the stream so signatures can be harvested without slowing or
    // breaking the caller's branch.
    if (response.body && url.includes(":streamGenerateContent")) {
      const [callerBranch, harvesterBranch] = response.body.tee();
      void consumeForSignatures(modelId, harvesterBranch);
      return new Response(callerBranch, {
        status: response.status,
        statusText: response.statusText,
        headers: response.headers,
      });
    }

    return response;
  };
}
